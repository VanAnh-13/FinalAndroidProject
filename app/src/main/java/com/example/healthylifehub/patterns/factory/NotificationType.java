package com.example.healthylifehub.patterns.factory;

/**
 * Factory Pattern - Notification Types
 */
public enum NotificationType {
    REMINDER,       // Nhắc nhở uống thuốc, khám bệnh
    ALERT,          // Cảnh báo chỉ số bất thường
    INFO,           // Thông tin chung
    ACHIEVEMENT,    // Thành tựu, mục tiêu đạt được
    SYNC            // Đồng bộ dữ liệu
}
